using UnityEngine;

namespace ParkIt
{
    /// <summary>Points the game at the imported car model (loaded from Resources/ParkItCarModel).</summary>
    [CreateAssetMenu(fileName = "ParkItCarModel", menuName = "Park It/Car Model Config", order = 2)]
    public class CarModelConfig : ScriptableObject
    {
        public const string ResourcePath = "ParkItCarModel";

        [Tooltip("Imported car model (FBX or prefab).")]
        public GameObject model;
        [Tooltip("Length of the car on the board in world units (one tile is 2). 1.71 matches the original procedural toy car.")]
        public float length = 1.71f;
        [Tooltip("Extra yaw so the model's nose points along +Z (North).")]
        public float yawOffset = 180f;
        [Tooltip("Renderers whose name contains this are treated as wheels and spin while driving.")]
        public string wheelNameContains = "Tire";

        [Header("Body Paint")]
        [Tooltip("Paint colour used by 'Park It > Recolor Car Body' to replace the model's blue body paint.")]
        public Color bodyColor = new Color(1f, .78f, .1f);
        [Tooltip("Name of the model material that carries the body paint.")]
        public string bodyMaterialName = "phong1";
        [Tooltip("Recoloured body material (generated by the menu command). Leave empty to keep the original paint.")]
        public Material bodyMaterial;

        [Header("Gameplay Colors")]
        public Material yellowBodyMaterial;
        public Material blueBodyMaterial;
        public Material greenBodyMaterial;
        public Material redBodyMaterial;
    }
}
